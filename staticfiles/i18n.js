const LANG_NAMES = { lo: "ພາສາລາວ", th: "ພາສາໄທ", en: "ພາສາອັງກິດ" };

window.NB_LANG = localStorage.getItem("nb_lang") || "lo";

function t(key) {
  return (I18N[window.NB_LANG] && I18N[window.NB_LANG][key]) || I18N.lo[key] || key;
}

function catName(id) {
  return t("cat_" + id);
}

function applyI18n() {
  document.documentElement.lang = window.NB_LANG;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  });
  document.querySelectorAll("[data-cat-name]").forEach((el) => {
    const slug = el.getAttribute("data-cat-name");
    if (!slug) return;
    const slugLower = slug.toLowerCase();
    const slugUnderscore = slugLower.replace(/-/g, "_");
    const translation = t("cat_" + slugUnderscore) || t("cat_" + slugLower);
    if (translation && !translation.startsWith("cat_")) {
      el.textContent = translation;
    }
  });
  document.querySelectorAll("[data-subcat-name]").forEach((el) => {
    const name = el.getAttribute("data-subcat-name");
    const direct = I18N[window.NB_LANG] && I18N[window.NB_LANG][name];
    if (direct) {
      el.textContent = direct;
      return;
    }
    const key = "subcat_" + name.toLowerCase().replace(/\s+/g, "_");
    const translation = t(key);
    if (translation && translation !== key) {
      el.textContent = translation;
    }
  });
  document.querySelectorAll("[data-p-name]").forEach((el) => {
    const pk = el.getAttribute("data-p-name");
    const translation = t("product_" + pk + "_name");
    if (translation && translation !== "product_" + pk + "_name") {
      el.textContent = translation;
    }
  });
  document.querySelectorAll("[data-p-desc]").forEach((el) => {
    const pk = el.getAttribute("data-p-desc");
    const translation = t("product_" + pk + "_desc");
    if (translation && translation !== "product_" + pk + "_desc") {
      el.textContent = translation;
    }
  });
  document.querySelectorAll("[data-order-status]").forEach((el) => {
    const status = el.getAttribute("data-order-status");
    const translation = t("order_status_" + status);
    if (translation && translation !== "order_status_" + status) {
      el.textContent = translation;
    }
  });
}

function setLang(lang) {
  localStorage.setItem("nb_lang", lang);
  window.NB_LANG = lang;
  applyI18n();
  if (typeof renderHeader === "function") renderHeader(window.__activePage || "");
  if (typeof renderFooter === "function") renderFooter();
  if (typeof onLangChange === "function") onLangChange();
}
